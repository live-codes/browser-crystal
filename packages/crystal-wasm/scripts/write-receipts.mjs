#!/usr/bin/env node
// Pin the assets: write src/asset-receipts.js from the bytes on disk.
//
//   node scripts/write-receipts.mjs
//
// Every read of an asset is checked against these receipts, so this is the step
// that says "these bytes, and no others". It runs at the end of build-assets.sh,
// and by hand after any change to the payload (a rebuilt compiler, a new library).
// The file it writes is committed: a receipt is only useful if it is the one the
// released package shipped with.
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, posix, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../assets/crystal/', import.meta.url));
const OUT = new URL('../src/asset-receipts.js', import.meta.url);

async function walk(dir) {
	const names = [];
	for (const entry of await readdir(dir, { withFileTypes: true })) {
		const path = join(dir, entry.name);
		if (entry.isDirectory()) names.push(...(await walk(path)));
		else names.push(path);
	}
	return names;
}

const files = await walk(ROOT);
if (files.length === 0) {
	console.error(`${ROOT} is empty — run build-assets.sh first.`);
	process.exit(1);
}

const receipts = {};
for (const file of files.sort()) {
	// posix separators: the name becomes a URL path in a browser and a fetch path
	// in Node, and neither wants a backslash.
	const name = relative(ROOT, file).split(sep).join(posix.sep);
	const bytes = await readFile(file);
	receipts[name] = {
		bytes: bytes.byteLength,
		sha256: createHash('sha256').update(bytes).digest('hex')
	};
}

const total = Object.values(receipts).reduce((sum, receipt) => sum + receipt.bytes, 0);
const body = `// Generated by scripts/write-receipts.mjs — do not edit by hand.
//
// The payload this package ships, pinned by content: every asset is checked
// against these bytes and this digest when it is read, so a stale copy, a
// truncated download or a host serving something else is named rather than
// compiled. ${Object.keys(receipts).length} files, ${(total / 1e6).toFixed(1)} MB gzipped.
//
// Re-pin with \`node scripts/write-receipts.mjs\` after rebuilding the assets.

export const ASSET_RECEIPTS = ${JSON.stringify(receipts, null, '\t')};
`;

await writeFile(OUT, body);
console.log(`Pinned ${Object.keys(receipts).length} assets, ${(total / 1e6).toFixed(1)} MB, in src/asset-receipts.js`);
for (const [name, { bytes }] of Object.entries(receipts)) {
	console.log(`  ${(bytes / 1e6).toFixed(2).padStart(8)} MB  ${name}`);
}
